// Builds the web workshop (node sim/build_web.js). Each page is a source file in web/*_app.html that gets the shared
// stylesheet, the navigation bar and its scripts; code and data shared between pages go to web/lib/ (plain <script>
// files, so the pages also work opened straight from disk):
//   web/index.html    Home            <- web/home_app.html (+ sub thumbnails in web/thumbs/)
//   web/subs.html     Sub Studio      <- web/subs_app.html      lib/sim.js lib/ships.js lib/circuits.js
//   web/sandbox.html  Circuit Lab     <- web/sandbox_app.html   lib/sim.js lib/lab.js
//   web/world.html    Drone Range     <- web/sandbox_app.html   lib/sim.js lib/lab.js (the lab page in world mode)
//   web/bench.html    Reactor Bench   <- web/bench_app.html     lib/sim.js lib/circuits.js lib/profiles.js
'use strict';
const fs = require('fs'), path = require('path'), zlib = require('zlib');
const ROOT = path.resolve(__dirname, '..'), WEB = path.join(ROOT, 'web');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const list = d => fs.existsSync(path.join(ROOT, d)) ? fs.readdirSync(path.join(ROOT, d)).sort() : [];
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(WEB, p)), { recursive: true }); fs.writeFileSync(path.join(WEB, p), s); return s.length; };
const js = (name, obj) => `self.${name} = ${JSON.stringify(obj).replace(/</g, '\\u003c')};\n`;
const sizes = {};

// ---------- lib/sim.js: every simulator module the pages use, in dependency order ----------
// structure prefab geometry (only what has a collision body, a platform or stairs) for true wall shapes
const prefabs = JSON.parse(read('ships/templates/structure_prefabs.json')).prefabs, bodies = {};
for (const [k, v] of Object.entries(prefabs)) if (v.body || v.platform || v.stairs) bodies[k] = v;
const MODULES = ['components', 'format', 'engine', 'project', 'autopins', 'subfile', 'shellgeom', 'label', 'world', 'ship', 'subrender', 'sandbox']
  .filter(m => fs.existsSync(path.join(ROOT, 'sim', m + '.js')));
sizes['lib/sim.js'] = write('lib/sim.js', ['// generated by sim/build_web.js from sim/*.js', 'self.BaroStructurePrefabs = ' + JSON.stringify({ prefabs: bodies }) + ';',
  ...MODULES.map(m => `// ---- sim/${m}.js\n` + read(`sim/${m}.js`))].join('\n;\n'));

// ---------- lib/ships.js: every sub under ships/vanilla and ships/custom as the light ship model ----------
const SF = require('./subfile'), R = require('./subrender');
const ships = {};
for (const dir of ['ships/vanilla', 'ships/custom']) for (const f of list(dir)) if (f.endsWith('.sub')) {
  const buf = fs.readFileSync(path.join(ROOT, dir, f)), xml = (buf[0] === 0x1f && buf[1] === 0x8b ? zlib.gunzipSync(buf) : buf).toString('utf8');
  const sh = SF.parseSub(xml); sh.file = dir + '/' + f; sh.vanilla = dir === 'ships/vanilla'; ships[sh.name] = sh;
}
sizes['lib/ships.js'] = write('lib/ships.js', js('BaroShips', ships));

// ---------- lib/circuits.js (reactor circuits + catalog) and lib/profiles.js (recorded power demand) ----------
const circuits = {};
for (const f of list('circuits')) if (f.endsWith('.circ')) circuits[f.replace(/\.circ$/, '')] = { circ: read('circuits/' + f), group: 'AI' };
// community / imported reactor circuits in Blueprints format (pairs: name_reactor.txt + name_battery.txt)
for (const f of list('context/reactor_circuits')) {
  if (!f.endsWith('.txt') || f.endsWith('_battery.txt')) continue;
  const bf = f.replace(/_reactor\.txt$/, '_battery.txt'), key = f.replace(/(_reactor)?\.txt$/, '');
  circuits[key] = { main: read('context/reactor_circuits/' + f), mainName: f, battery: bf !== f && list('context/reactor_circuits').includes(bf) ? read('context/reactor_circuits/' + bf) : null, group: 'Community' };
  const pf = [f.replace(/\.txt$/, '.pins'), key + '.pins'].find(p => list('context/reactor_circuits').includes(p)); if (pf) circuits[key].pins = read('context/reactor_circuits/' + pf);
}
const catalog = fs.existsSync(path.join(ROOT, 'circuits/catalog.json')) ? JSON.parse(read('circuits/catalog.json')) : null;
sizes['lib/circuits.js'] = write('lib/circuits.js', js('BaroCircuitLib', { circuits, catalog }));
// Real round logs can be huge (a 64-minute round is ~18 MB). Keep only rows where something the simulator replays
// changed (rods/fuel at once; demand >= 20 kW or a pin >= 5 at most 5 times a second), at least every 5 s, and bake in
// the rod fuel worked out from the full log.
const E = require('./engine');
function thin(text, name) {
  if (text.length < 3e5) return text;
  const prof = E.parseProfile(text, name);
  const ch = prof.channels, head = text.split(/\r?\n/).filter(l => l.startsWith('#') && !/duration/.test(l));
  const L = [...head, `# duration=${prof.duration}`, ['t', 'demand', 'rods', 'avail_fuel', 'fuel', ...ch].join(',')];
  let last = null;
  for (const p of prof.points) {
    const row = [p.demand, p.rods ?? '', p.rodFuel && p.rods !== undefined ? p.rodFuel * p.rods : '', p.g.fuelPct ?? '', ...ch.map(c => p.ch[c] ?? '')];
    const keep = !last || p.t - last.t >= 5 || row[1] !== last.row[1] || row[2] !== last.row[2] || Math.abs((row[3] || 0) - (last.row[3] || 0)) >= 1
      || (p.t - last.t >= 0.2 && (Math.abs(row[0] - last.row[0]) >= 20 || row.slice(4).some((v, i) => Math.abs((v || 0) - (last.row[i + 4] || 0)) >= 5)));
    if (!keep) continue;
    L.push([p.t.toFixed(2), ...row.map(v => typeof v === 'number' ? (Math.round(v * 10) / 10) : v)].join(','));
    last = { t: p.t, row };
  }
  return L.join('\n') + '\n';
}
const profiles = {}; for (const f of list('load_profiles')) if (f.endsWith('.csv')) profiles[f.replace(/\.csv$/, '')] = thin(read('load_profiles/' + f), f);
sizes['lib/profiles.js'] = write('lib/profiles.js', js('BaroProfiles', profiles));

// ---------- lib/lab.js: sandbox examples, world (drone range) examples, and every circuit file for `box file=` ----------
const files = {}, walk = d => { for (const f of list(d)) { const p = d + '/' + f; if (fs.statSync(path.join(ROOT, p)).isDirectory()) walk(p); else if (/\.(circ|txt)$/.test(f)) files[p] = read(p); } };
walk('circuits');
const examples = {}; for (const f of list('sandbox')) if (f.endsWith('.sbx')) examples[f.replace(/\.sbx$/, '')] = read('sandbox/' + f);
const worlds = {}; for (const f of list('sandbox/world')) if (f.endsWith('.sbx')) worlds[f.replace(/\.sbx$/, '')] = read('sandbox/world/' + f);
sizes['lib/lab.js'] = write('lib/lab.js', js('BaroLabLib', { examples, worlds, files }));

// ---------- thumbnails for the home page: each sub's true outline, rooms and items, no wires ----------
const thumbs = [];
for (const sh of Object.values(ships)) {
  const base = !sh.vanilla ? Object.values(ships).find(b => b.vanilla && sh.name.toLowerCase().startsWith(b.name.toLowerCase())) : null;
  const r = R.render(sh, { width: 640, wires: 'none', labels: 'none', props: false, base, pad: 60, minItemPx: 2 });
  const file = 'thumbs/' + sh.name.replace(/[^\w.-]+/g, '_') + '.svg';
  sizes[file] = write(file, r.svg);
  thumbs.push({ name: sh.name, file, base: base ? base.name : null, vanilla: sh.vanilla, rooms: sh.hulls.length, items: sh.items.length, wires: sh.wires.length, boxes: sh.items.filter(i => i.box).length, w: r.width, h: r.height });
}

// ---------- pages ----------
const PAGES = [
  { file: 'index.html', src: 'home_app.html', nav: 'Home', libs: [] },
  { file: 'subs.html', src: 'subs_app.html', nav: 'Sub Studio', libs: ['lib/sim.js', 'lib/ships.js', 'lib/circuits.js'] },
  { file: 'sandbox.html', src: 'sandbox_app.html', nav: 'Circuit Lab', libs: ['lib/sim.js', 'lib/lab.js'] },
  { file: 'world.html', src: 'sandbox_app.html', nav: 'Drone Range', libs: ['lib/sim.js', 'lib/lab.js'], mode: 'world', title: 'Drone Range' },
  { file: 'bench.html', src: 'bench_app.html', nav: 'Reactor Bench', libs: ['lib/sim.js', 'lib/circuits.js', 'lib/profiles.js'] },
].filter(p => fs.existsSync(path.join(WEB, p.src)));
const ICON = '<svg viewBox="0 0 32 32" aria-hidden="true"><path d="M4 18c0-4 5-7 12-7h4l2-4h3l-1 4c3 1 5 3 5 7s-5 6-13 6S4 22 4 18z" fill="currentColor" opacity=".9"/><circle cx="12" cy="18" r="1.8" fill="var(--bg)"/><circle cx="17" cy="18" r="1.8" fill="var(--bg)"/><circle cx="22" cy="18" r="1.8" fill="var(--bg)"/></svg>';
function nav(current) {
  const links = PAGES.map(p => `<a href="${p.file}"${p.nav === current ? ' aria-current="page"' : ''}>${p.nav}</a>`).join('');
  return `<header class="topnav"><a class="brand" href="index.html">${ICON}Barotrauma Workshop</a><nav aria-label="Pages">${links}</nav><span class="spacer"></span>`
    + `<button class="themebtn" type="button" title="Light or dark" aria-label="Switch between light and dark"><svg viewBox="0 0 20 20" width="16" height="16" aria-hidden="true"><circle cx="10" cy="10" r="7.5" fill="none" stroke="currentColor" stroke-width="1.6"/><path d="M10 2.5a7.5 7.5 0 0 1 0 15z" fill="currentColor"/></svg></button></header>`
    + `<script>(()=>{const k='bw.theme',r=document.documentElement;try{const t=localStorage.getItem(k);if(t)r.dataset.theme=t}catch(e){}document.currentScript.previousElementSibling.querySelector('.themebtn').onclick=()=>{const d=r.dataset.theme?r.dataset.theme==='dark':matchMedia('(prefers-color-scheme: dark)').matches;r.dataset.theme=d?'light':'dark';try{localStorage.setItem(k,r.dataset.theme)}catch(e){}}})()</script>`;
}
const css = read('web/shared.css');
write('shared.css', css);
for (const p of PAGES) {
  let html = read('web/' + p.src);
  const scripts = p.libs.map(l => `<script src="${l}"></script>`).join('\n');
  html = html.replace('<!--SHARED-->', '<link rel="stylesheet" href="shared.css">')
    .replace('<!--NAV-->', () => nav(p.nav))
    .replace('<!--LIBS-->', () => scripts)
    .replace('<!--MODE-->', () => p.mode ? `<script>self.LAB_MODE = '${p.mode}';</script>` : '')
    .replace(/<title>[^<]*<\/title>/, t => p.title ? `<title>${p.title}</title>` : t)
    .replace('/*__THUMBS__*/', () => JSON.stringify(thumbs).replace(/</g, '\\u003c'))
    .replace('/*__PAGES__*/', () => JSON.stringify(PAGES.map(q => ({ file: q.file, nav: q.nav }))));
  sizes[p.file] = write(p.file, html);
}
// pages from before the split: the old bench lived at index.html (now the home page)
for (const old of ['app.html']) if (fs.existsSync(path.join(WEB, old)) && fs.existsSync(path.join(WEB, 'bench_app.html'))) fs.unlinkSync(path.join(WEB, old));
for (const [f, n] of Object.entries(sizes)) if (!f.startsWith('thumbs/')) console.log(`web/${f}: ${(n / 1024).toFixed(0)} KB`);
console.log(`web/thumbs: ${thumbs.length} subs; lib/sim.js modules: ${MODULES.join(', ')}`);
