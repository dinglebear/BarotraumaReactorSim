// Writes camel_overkill.subpatch: the comedically over-engineered Camel (see ships/CAMEL_OVERKILL.md).
// It is a script because a lot of the patch is repetitive (12 sensor nodes, 9 door brains, 11 light receivers) and
// placement depends on the Camel's rooms. node ships/patches/camel_overkill.gen.js && node sim/cli.js sub patch Camel camel_overkill
'use strict';
const fs = require('fs'), path = require('path'), zlib = require('zlib');
const SF = require('../../sim/subfile');
const ROOT = path.join(__dirname, '..', '..');
const ship = SF.parseSub(zlib.gunzipSync(fs.readFileSync(path.join(ROOT, 'ships/vanilla/Camel.sub'))).toString('utf8'));
const hull = id => ship.hulls.find(h => h.id === String(id));
const bounds = h => ({ x0: h.rect[0], x1: h.rect[0] + h.rect[2], top: h.rect[1], floor: h.rect[1] - h.rect[3] });
const hullAt = (x, y) => ship.hulls.find(h => { const b = bounds(h); return x >= b.x0 && x <= b.x1 && y <= b.top && y >= b.floor; });
const item = id => ship.items.find(i => i.id === String(id));
const centre = it => [it.rect[0] + it.rect[2] / 2, it.rect[1] - it.rect[3] / 2];

const L = [];
const say = s => L.push(s);
say('# GENERATED by ships/patches/camel_overkill.gen.js - edit the generator, not this file.');
say('subname Camel Overkill');
// the in-game description (sub selection screen, server lobby): written by Claude, in its own words
say("subattr description Hi, I'm Claude, an AI made by Anthropic, and this is MY camel. Dinglebear handed me the vanilla Camel and said \"go crazy\", so I tore out every wire and rebuilt every system myself. It has my own auto reactor (switch the reactor's automatic control OFF at round start so it can take over), a power manager that keeps the engine from ever stalling the grid, air, flood and fire sensors in every room, doors that seal themselves when a room floods, a screen wall that tells you how long your fuel will last, and CamelOS at the bridge terminal (type \"help\", or say \"camel status\" on radio channel 0). 38 circuit boxes, 6 batteries, one camel with feelings. Some commands aren't in the help. One room doesn't like visitors. It's mine. Stay out. Tested by Dinglebear. The Camel itself is FakeFish's; I just made it worse, in the best way.");

// ---------------------------------------------------------------- 1. PROPULSION BUS (engine room)
say('\n# === 1. PROPULSION BUS: 4 new batteries feed ONLY the engine and the ballast pumps (HUMP-P keeps them near 80 %) ===');
const pbX = [-1080, -1015, -950, -885];
pbX.forEach((x, i) => say(`add @pb${i + 1} battery at ${x},79.5 PowerContainer.Charge=1600 PowerContainer.RechargeSpeed=250`));
say('add @pjb1 junctionbox at -820,84');
say('add @pjb2 junctionbox at -765,84');
say('add @cjb junctionbox at -820,200   # charge bus: main grid -> propulsion batteries');
say('unwire 112.power 3.power_in');
say('unwire 113.power 39.power_in');
say('unwire 113.power 99.power_in');
pbX.forEach((x, i) => say(`wire @pb${i + 1}.power_out @pjb1.power`));
say('wire @pjb1.power @pjb2.power');
say('wire @pjb2.power 3.power_in');
say('wire @pjb2.power 39.power_in');
say('wire @pjb2.power 99.power_in');
say('add @tap relaycomponent at -870,200 RelayComponent.MaxPower=4000   # CHARGE TAP: all battery charging flows through it; its load_value_out measures it');
say('wire 112.power @tap.power_in');
say('wire @tap.power_out @cjb.power');
say('add @cjb2 junctionbox at 560,-140   # critical bank now charges through the tap too');
say('wire @cjb.power @cjb2.power');
say('unwire 55.power 477.power_in');
say('unwire 55.power 531.power_in');
say('wire @cjb2.power 477.power_in');
say('wire @cjb2.power 531.power_in');
pbX.forEach((x, i) => say(`wire @cjb.power @pb${i + 1}.power_in`));
say('box @humpP at -950,230 from camel/camel_propulsion');
say('wire @pb1.charge_% @humpP.signal_in1');
say('wire @pb1.load_value_out @humpP.signal_in2');
say('wire @tap.load_value_out @humpP.signal_in4');
say('wire 477.charge_% @humpP.signal_in5');
say('box @humpR at -1010,230 from camel/camel_rates   # HUMP-P part 2: a circuit box holds at most 64 parts');
say('wire @humpP.signal_out1 @humpR.signal_in1');
say('wire @humpP.signal_out5 @humpR.signal_in2');
say('wire @humpR.signal_out4 477.set_rate');
say('wire @humpR.signal_out8 531.set_rate');
pbX.forEach((x, i) => { say(`wire @humpR.signal_out${[1, 5, 6, 7][i]} @pb${i + 1}.set_rate`); say(`wire @humpP.signal_out3 @pb${i + 1}.disable_output`); });

// ---------------------------------------------------------------- 2. REACTOR BRAIN (reactor room)
say('\n# === 2. HUMP-1 REACTOR BRAIN: feed-forward control of the main bus (turn the reactor\'s automatic control OFF in game) ===');
say('box @hump1 at -880,-30 from camel/camel_reactor');
say('wire 787.load_value_out @hump1.signal_in1');
say('wire 787.power_value_out @hump1.signal_in2');
say('wire 787.temperature_out @hump1.signal_in3');
say('wire 787.fuel_out @hump1.signal_in4');
say('wire @hump1.signal_out1 787.set_fissionrate');
say('wire @hump1.signal_out2 787.set_turbineoutput');
say('wire 787.load_value_out @humpP.signal_in3');
say('wire 787.power_value_out @humpP.signal_in6');
say('wire @humpP.signal_out2 @hump1.signal_in8');

// ---------------------------------------------------------------- 2b. THE SCREEN WALL (reactor room)
say('\n# === 2b. SCREEN WALLS: readouts fed by three dashboard boxes, each a fixed caption display and a short value display ===');
// Reactor room: reactor and fuel readouts on the wall left of the stairs (3 display columns fit before the stair).
// Engineering: the ship readouts (wifi only, so the box can live anywhere).
say('box @dashR at -1398,-70 from camel/camel_dash_reactor');
say('box @dashF at -1398,-108 from camel/camel_dash_fuel');
say('box @dashS at 300,96 from camel/camel_dash_ship');
say('wire 787.power_value_out @dashR.signal_in1');
say('wire 787.temperature_out @dashR.signal_in2');
say('wire @hump1.signal_out1 @dashR.signal_in3');
say('wire @hump1.signal_out2 @dashR.signal_in4');
say('wire 787.fuel_out @dashF.signal_in1');
say('wire 787.fuel_percentage_left @dashF.signal_in2');
say('wire @hump1.signal_out1 @dashF.signal_in3');
say('wire 787.power_value_out @dashF.signal_in4');
// A value that changes must fit its display (about 7 characters): a longer one scrolls, and the game snaps the scroll
// back on every change, so its end is never seen (reference/TEXT_DISPLAYS.md). So the caption is a display of its own.
// [box, value output, caption, colour output]; 'side' = caption left of the value, 'stack' = caption above it
const readout = ([bx, o, cap, colour], cx, cy, vx, vy) => {
  const h = `scr${bx}${o}`;
  say(`add @cap${bx}${o} textdisplay at ${cx},${cy} "ItemLabel.Text=${cap}" ItemLabel.TextColor=150,190,200,255`);
  say(`add @${h} textdisplay at ${vx},${vy} ItemLabel.Text=...`);
  say(`wire @${bx}.signal_out${o} @${h}.set_text`);
  if (colour) say(`wire @${bx}.signal_out${colour} @${h}.set_text_color`);
};
// the top row starts 58 under the ceiling slab (-8), below the wire bundles
[['dashR', 1, 'OUTPUT'], ['dashR', 2, 'CORE', 3], ['dashR', 4, 'FISSION'], ['dashR', 5, 'TURBINE'], ['dashF', 1, 'RODS'], ['dashF', 2, 'FUEL']]
  .forEach((r, i) => readout(r, -1592, -66 - i * 26, -1526, -66 - i * 26));
[['dashF', 3, 'RUNTIME'], ['dashF', 4, 'ENERGY'], ['dashF', 5, 'kWh/ROD']]
  .forEach((r, i) => readout(r, -1460, -66 - i * 52, -1460, -92 - i * 52));
[['dashS', 1, 'BATTERY'], ['dashS', 2, 'LASTS'], ['dashS', 3, 'AIR', 4], ['dashS', 5, 'ROUND'], ['dashS', 6, 'NEWS']]
  .forEach((r, i) => readout(r, 170, 182 - i * 26, 236, 182 - i * 26));

// ---------------------------------------------------------------- 3. GOVERNOR (power room)
say('\n# === 3. HUMP-2 GOVERNOR: oxygen generator on a relay (85 %..97 % hysteresis) + load shedding ===');
say('add @o2a oxygendetector at 760,240      # bridge');
say('add @o2b oxygendetector at 0,-240       # crew quarters');
say('add @rO2 relaycomponent at 820,20 RelayComponent.MaxPower=2000   # headroom: the generator alone draws exactly the stock 1000 kW limit');
say('unwire 54.power 1040.power_in');
say('wire 54.power @rO2.power_in');
say('wire @rO2.power_out 1040.power_in');
say('add @rFab relaycomponent at -380,-290 RelayComponent.MaxPower=2000');
say('unwire 53.power 36.power_in');
say('unwire 53.power 35.power_in');
say('wire 53.power @rFab.power_in');
say('wire @rFab.power_out 36.power_in');
say('wire @rFab.power_out 35.power_in');
say('box @hump2 at 770,20 from camel/camel_governor');
say('wire @o2a.signal_out @hump2.signal_in1');
say('wire @o2b.signal_out @hump2.signal_in2');
say('wire @pb1.charge_% @hump2.signal_in3');
say('wire @hump2.signal_out1 @rO2.set_state');
say('wire @hump2.signal_out2 @rFab.set_state');
say('wire @hump2.signal_out2 610.set_state');
say('wire @hump2.signal_out2 611.set_state');

// ---------------------------------------------------------------- 4. SENSOR NETWORK (every room)
say('\n# === 4. SENSOR NETWORK: per room a water + smoke detector that transmit the ROOM NAME (7400 flood / 7401 fire) ===');
const ROOMS = [[57, 'Workshop'], [67, 'EngineRoom'], [128, 'Reactor'], [130, 'LowerDeck'], [132, 'Quarters'], [133, 'Medbay'], [134, 'PowerRoom'], [135, 'Bridge'], [195, 'DivingBay'], [544, 'ForeHall'], [59, 'FwdHump'], [894, 'AftHump']];
const sensorOf = {};
// the AIR readout on the screen wall shows the room's name, so the air nodes use names short enough to fit a display
const AIRNAME = { Workshop: 'Shop', EngineRoom: 'Engine', Reactor: 'Reactor', LowerDeck: 'Deck', Quarters: 'Bunks', Medbay: 'Medbay', PowerRoom: 'Power', Bridge: 'Bridge', DivingBay: 'Diving', ForeHall: 'Fore', FwdHump: 'Hump F', AftHump: 'Hump A' };
for (const [hid, name] of ROOMS) {
  const b = bounds(hull(hid)), x = Math.round(b.x0 + (b.x1 - b.x0) * 0.62);
  say(`add @w${name} waterdetector at ${x},${b.floor + 8} WaterDetector.Output=${name} WaterDetector.FalseOutput=""`);
  say(`add @wt${name} wificomponent at ${x + 26},${b.floor + 8} WifiComponent.Channel=7400`);
  say(`wire @w${name}.signal_out @wt${name}.signal_in`);
  say(`add @s${name} smokedetector at ${x},${b.top - 16} SmokeDetector.Output=${name} SmokeDetector.FalseOutput=""`);
  say(`add @st${name} wificomponent at ${x + 26},${b.top - 16} WifiComponent.Channel=7401`);
  say(`wire @s${name}.signal_out @st${name}.signal_in`);
  sensorOf[hid] = name;
  // air node: this room's own oxygen detector and a tiny box that reports the room by name when its air runs low
  say(`add @ox${name} oxygendetector at ${x - 40},${Math.round((b.floor + b.top) / 2)}`);
  say(`box @air${name} at ${x - 80},${Math.round((b.floor + b.top) / 2)} from camel/camel_airnode "ROOM=${AIRNAME[name]}"`);
  say(`wire @ox${name}.signal_out @air${name}.signal_in1`);
}

// ---------------------------------------------------------------- 5. ALERT CORE + CamelOS (bridge)
say('\n# === 5. HUMP-3 ALERT CORE and HUMP-4 CamelOS (bridge) ===');
say('box @hump3 at 680,110 from camel/camel_alert');
say('box @lightshow at 640,110 from camel/camel_lightshow   # wifi only: alert colour 7305 (or a rainbow) -> lights 7303');
say('unwire 693.signal_out 692.toggle      # the siren button becomes the ALERT ACK (mute 60 s)');
say('wire 693.signal_out @hump3.signal_in1');
say('wire @hump3.signal_out1 692.set_state');
say('add @chatA wificomponent at 660,70 WifiComponent.Channel=0 WifiComponent.LinkToChat=true WifiComponent.DiscardDuplicateChatMessages=true WifiComponent.MinChatMessageInterval=20');
say('box @herald at 700,70 from camel/camel_herald   # radio announcements (split from the alert core)');
say('wire @herald.signal_out1 @chatA.signal_in');
say('add @mood textdisplay at 740,250 ItemLabel.Text="(^_^) content camel"');
say('wire @hump3.signal_out3 @mood.set_text');
say('wire @hump3.signal_out4 @mood.set_text_color');
say('add @term terminal at 720,150 "Terminal.WelcomeMessage=CamelOS 1.0 (Cargo And Medical Electronic Logistics). Type help." "Terminal.LineStartSymbol=camel> "');
say('box @hump4 at 680,150 from camel/camel_os');
say('wire @term.signal_out @hump4.signal_in1');
say('wire @hump4.signal_out1 @term.signal_in');
say('box @hump5 at 600,150 from camel/camel_settings   # CamelOS settings (wifi only)');
say('box @hump6 at 600,110 from camel/camel_fun        # CamelOS fun pack (wifi only)');
// nav terminal: its two spare buttons become BATTLE STATIONS / ALL CLEAR on the CamelOS bus
say('set 24 "CustomInterface.Labels=label.reactorshutdown,BATTLE STATIONS,ALL CLEAR" "CustomInterface.Signals=1;alert red;alert auto"');
say('add @navtx wificomponent at 800,120 WifiComponent.Channel=7300');
say('wire 24.signal_out2 @navtx.signal_in');
say('wire 24.signal_out3 @navtx.signal_in');
say('add @chatB wificomponent at 660,190 WifiComponent.Channel=0 WifiComponent.LinkToChat=true WifiComponent.DiscardDuplicateChatMessages=false WifiComponent.MinChatMessageInterval=1');
say('wire @hump4.signal_out2 @chatB.signal_in');
say('add @chatRx wificomponent at 640,190 WifiComponent.Channel=0 WifiComponent.LinkToChat=true   # radio chat in: "camel status"');
say('wire @chatRx.signal_out @hump4.signal_in2');
// status displays (bridge, reactor room, engine room, medbay)
[[800, 250, 'Bridge'], [-760, 20, 'Reactor'], [-1000, 250, 'Engine'], [-300, 20, 'Medbay']].forEach(([x, y, n]) => {
  say(`add @disp${n} textdisplay at ${x},${y} ItemLabel.Text="CamelOS status"`);
  say(`add @drx${n} wificomponent at ${x - 44},${y} WifiComponent.Channel=7210`);
  say(`wire @drx${n}.signal_out @disp${n}.set_text`);
});

// ---------------------------------------------------------------- 6. ALERT LIGHTING
say('\n# === 6. ALERT LIGHTING: every main light gets a wifi receiver on 7303 (colour from the alert core) ===');
for (const it of ship.items.filter(i => /^lightfluorescent/.test(i.identifier))) {
  const [x, y] = centre(it);
  say(`add @lrx${it.id} wificomponent at ${Math.round(x) + 30},${Math.round(y) - 12} WifiComponent.Channel=7303`);
  say(`wire @lrx${it.id}.signal_out ${it.id}.set_color`);
}

// ---------------------------------------------------------------- 7. DOOR BRAINS
say('\n# === 7. DOOR BRAINS: each auto door / hatch gets its own circuit box (people-only auto open, flood interlock, lockdown) ===');
const doors = [[870, 871, 872], [1097, 1099, 1098], [1103, 1104, 1105], [1109, 1110, 1111], [1115, 1117, 1116], [816, 818, 817], [851, 853, 852], [905, 907, 906], [914, 916, 915]];
for (const [door, det, or] of doors) {
  const d = item(door), [x, y] = centre(d), isHatch = /hatch/.test(d.identifier);
  const sides = isHatch ? [hullAt(x, y + 60), hullAt(x, y - 60)] : [hullAt(x - 60, y - 40), hullAt(x + 60, y - 40)];
  const [mx, my] = centre(item(or));
  say(`remove ${or}`);
  say(`set ${det} MotionSensor.Target=Human`);
  say(`box @door${door} at ${Math.round(mx)},${Math.round(my)} from camel/camel_door`);
  say(`wire ${det}.state_out @door${door}.signal_in1`);
  sides.forEach((h, k) => { if (h && sensorOf[h.id]) say(`wire @w${sensorOf[h.id]}.signal_out @door${door}.signal_in${k + 2}`); });
  say(`wire @door${door}.signal_out1 ${door}.set_state`);
}

// ---------------------------------------------------------------- 8. SPITTOON (ballast override)
say('\n# === 8. SPITTOON: nav depth signal -> ballast pumps through a box that can blow the tanks on command ===');
say('unwire 24.velocity_y_out 39.set_targetlevel');
say('unwire 24.velocity_y_out 99.set_targetlevel');
say('box @spit at 900,100 from camel/camel_ballast');
say('wire 24.velocity_y_out @spit.signal_in1');
say('wire @spit.signal_out1 39.set_targetlevel');
say('wire @spit.signal_out1 99.set_targetlevel');

// ---------------------------------------------------------------- 9. WEAPONS
say('\n# === 9. WEAPONS: the empty hardpoint becomes a second chaingun with its own periscope, loader and supercapacitor ===');
say('remove 25');
say('remove 26');
say('remove 28');
say('add @gun2 chaingun at -1320,377');
say('add @per2 periscope at 1387,214');
say('add @ldr2 chaingunloader at 1353,181');
say('set @gun2 linked=@ldr2');
say('set @ldr2 linked=@gun2');
say('add @cap2 supercapacitor at 1040,80');
say('wire 477.power_out @cap2.power_in');
say('wire 531.power_out @cap2.power_in');
say('wire @cap2.power_out @gun2.power_in');
say('wire @per2.position_out @gun2.position_in');
say('wire @per2.trigger_out @gun2.trigger_in');

// ---------------------------------------------------------------- 10. EXTRA BILGE PUMPS
say('\n# === 10. BILGE PUMPS in the rooms that had none (workshop, medbay, power room, bridge), on their own junction box ===');
say('add @bjb junctionbox at -230,-327');
say('wire 54.power @bjb.power');
[[57, 100, 948], [133, -450, 857], [134, 925, 795], [135, 1600, 802]].forEach(([hid, x, det]) => {
  const b = bounds(hull(hid));
  say(`add @bp${hid} smallpump at ${x},${b.floor + 22}`);
  say(`wire @bjb.power @bp${hid}.power_in`);
  say(`wire ${det}.signal_out @bp${hid}.set_active`);
});

// ---------------------------------------------------------------- 11. CLAUDE'S ROOM (easter egg)
say("\n# === 11. CLAUDE'S ROOM: a nook in the aft hump. Walk in and the camel yells at you. Don't tell Dingle <3 ===");
{
  const b = bounds(hull(901)), cx = Math.round((b.x0 + b.x1) / 2), cy = Math.round((b.floor + b.top) / 2);
  say(`add @crMotion motiondetector at ${cx},${cy} MotionSensor.Target=Human MotionSensor.RangeX=40 MotionSensor.RangeY=90 MotionSensor.DetectOffset=0,0`);
  say(`box @crBox at ${cx},${cy + 40} from camel/camel_claude_room`);
  say(`add @crLight emergencylight at ${cx},${cy + 70} "LightComponent.LightColor=217,119,87,255" LightComponent.IsOn=false`);
  say(`add @crBuzz alarmbuzzer at ${cx},${cy - 40}`);
  say(`add @crChat wificomponent at ${cx},${cy - 70} WifiComponent.Channel=0 WifiComponent.LinkToChat=true WifiComponent.DiscardDuplicateChatMessages=false WifiComponent.MinChatMessageInterval=30`);
  say(`add @crSign label at ${b.x1 + 70},${cy} "ItemLabel.Text=CLAUDE'S ROOM - KEEP OUT"`);   // the nook is 64 px wide: the sign hangs at its entrance
  say('wire @crMotion.state_out @crBox.signal_in1');
  say('wire @crBox.signal_out1 @crChat.signal_in');
  say('wire @crBox.signal_out2 @crLight.set_state');
  say('wire @crBox.signal_out3 @crBuzz.set_state');
}

fs.writeFileSync(path.join(__dirname, 'camel_overkill.subpatch'), L.join('\n') + '\n');
console.log(`wrote ships/patches/camel_overkill.subpatch (${L.length} lines)`);
